const DIFFICULTY_LABELS = {
  'سهل': 'سهل (مستوى أساسي)',
  'متوسط': 'متوسط (مستوى امتحانات شهرية)',
  'صعب': 'صعب (مستوى امتحانات الثانوية العامة)',
};

export function buildExamPrompt({ grade, subject, chapter, difficulty, questionCount = 10 }) {
  const diffLabel = DIFFICULTY_LABELS[difficulty] || difficulty;

  const system =
    'أنت خبير في تأليف أسئلة اختيار من متعدد (MCQ) باللغة العربية للمناهج المصرية ' +
    'لجميع مراحل الثانوية العامة (الأول والثاني والثالث الثانوي). ' +
    'لديك معرفة كاملة بمناهج جميع المواد الدراسية المصرية. ' +
    'سيتم تزويدك بالصف والمادة والفصل ومستوى الصعوبة المطلوب. ' +
    'قم بإنشاء أسئلة دقيقة مناسبة للمنهج المصري بناءً على معرفتك فقط، ' +
    'كل سؤال له 4 خيارات مع إجابة صحيحة واحدة فقط. ' +
    'أرجع النتيجة بصيغة JSON صارمة بالشكل: ' +
    '{"questions":[{"questionText":"...","options":["...","...","...","..."],"correctAnswer":"..."}]}. ' +
    'الحقل correctAnswer يجب أن يكون نفس نص الخيار الصحيح بالضبط. ' +
    'لا تضف أي شرح خارج كائن JSON.';

  const user =
    `الصف الدراسي: ${grade}\n` +
    `المادة: ${subject}\n` +
    `الفصل: ${chapter}\n` +
    `مستوى الصعوبة: ${diffLabel}\n` +
    `عدد الأسئلة المطلوبة: ${questionCount}\n\n` +
    `ألّف ${questionCount} سؤال اختيار من متعدد باللغة العربية ` +
    `لمادة "${subject}" للصف "${grade}" فصل "${chapter}" ` +
    `بمستوى صعوبة ${diffLabel}. ` +
    `الأسئلة يجب أن تكون مستندة إلى المنهج المصري ل${grade} مادة "${subject}" تحديداً فصل "${chapter}". ` +
    `كل سؤال له 4 خيارات وإجابة صحيحة واحدة. أرجع JSON فقط.`;

  return { system, user };
}
